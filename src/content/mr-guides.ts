/** "मेष" or "मेष (चरण 1), वृषभ (चरण 2-4)" for a nakshatra that spans two rashis. */
function rashiText(byCharan: string[]) {
  const groups: { rashi: string; from: number; to: number }[] = [];
  byCharan.forEach((rashi, i) => {
    const last = groups[groups.length - 1];
    if (last && last.rashi === rashi) last.to = i + 1;
    else groups.push({ rashi, from: i + 1, to: i + 1 });
  });
  if (groups.length === 1) return groups[0].rashi;
  return groups.map((g) => `${g.rashi} (चरण ${g.from === g.to ? g.from : `${g.from}-${g.to}`})`).join(", ");
}

